-- ------------------------------------------------------------------
-- 0003_admin_role : users に role を追加
--
-- role は user / admin の2値。既定は全員 user。
-- admin は開発者用で、settingページ（DBの中身の閲覧・CSVダウンロード、
-- 他ユーザーのrole変更）にアクセスできる。
--
-- 管理者の指定は基本的にsettingページの操作(POST /api/admin/users/:id/role)
-- から行う想定。最初の1人だけは、このマイグレーションの後にDBへ直接
-- 書き込んで用意する（settingページを開ける人がまだ誰もいないため）。
--
-- 付記（スキーマ変更ではないのでここに書く。0002は適用済みのため書き換えない）:
-- app_sessions.poll_id はこれまで「セッション開始時点で見ていた募集」だけを
-- 記録していたが、画面遷移のたびに最新の値へ上書きするようワーカー側の
-- 挙動を変更した。投票詳細ページ以外にいる間はnullに戻すので、
-- last_screen='poll' かつ poll_id=<X> で「Xの詳細ページで離脱した」と
-- 特定できるようになった。
-- ------------------------------------------------------------------

ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'user';
